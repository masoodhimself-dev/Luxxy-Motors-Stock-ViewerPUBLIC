/** Match only known makes; never construct an asset path from user-supplied text. */
export function getMakeLogoSrc(make: string | null | undefined): string | null {
  const key = (make ?? '')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]/g, '');
  const canonical = Object.hasOwn(MAKE_ALIASES, key) ? MAKE_ALIASES[key] : key;
  return Object.hasOwn(MAKE_LOGO_FILES, canonical)
    ? `/brand/car-makes/${MAKE_LOGO_FILES[canonical]}`
    : null;
}
