import {test,expect} from '@playwright/test';
import {mkdir} from 'node:fs/promises';
test.skip(process.env.LUXXY_LOCAL_PREVIEW!=='1','Fictional local enquiries only.');
for(const width of [390,834,1440])test(`tidy part exchange and customer actions at ${width}`,async({page})=>{
 await page.setViewportSize({width,height:1000});
 const errors:string[]=[],writes:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/api/**',route=>{if(route.request().method()==='GET')return route.continue();writes.push(route.request().url());return route.abort();});
 const id='00000000-0000-4000-8000-000000000992';
 const message='Hello, I would like to discuss a part exchange.\n\nMY CURRENT CAR\nRegistration: AB12 CDE\nMake / model: Volkswagen Polo\nMileage: 38,000 miles\nDamage / faults / other details: Scratch on driver door\n\nYOUR STOCK VEHICLE\nSkoda Superb\nYear: 2017\nAdvertised price: GBP 8,244\n\nMY CONTACT DETAILS\nName: Fictional Customer\nPhone: 07700900123\n\nPlease let me know what you need for a valuation.';
 await page.route('**/api/enquiries',r=>r.fulfill({json:[{id,reference:'HIDDEN',type:'part_exchange',source:'website',status:'new',customerName:'Fictional Customer',phone:'07700900123',email:'buyer@example.test',preferredContact:'phone',vehicleId:null,vehicleTitle:'Skoda Superb',message,workspaceRevision:1,followUpRevision:1,createdAt:'2026-10-23T10:00:00Z',events:[]}]}));
 await page.route('**/api/staff/email/reply-attention',r=>r.fulfill({json:{enquiries:[]}}));
 await page.route(`**/api/staff/enquiries/${id}/conversations`,r=>r.fulfill({json:{events:[],total:0,nextCursor:null}}));
 await page.goto('/portal?section=notifications&workView=customers');
 await page.getByRole('button',{name:'Open enquiry for Fictional Customer, Skoda Superb',exact:true}).click();
 const detail=page.getByRole('region',{name:'Selected enquiry: Fictional Customer'});
 await expect(detail.getByRole('region',{name:"Customer's part-exchange car"})).toBeVisible();
 await expect(detail.getByText('Scratch on driver door',{exact:true})).toBeVisible();
 await expect(detail.getByText('MY CONTACT DETAILS',{exact:false})).not.toBeVisible();
 await expect(detail.getByRole('button',{name:'Record the response',exact:true})).toBeVisible();
 await expect(detail.getByRole('button',{name:'Book test drive',exact:true})).toBeVisible();
 await detail.getByText('View full original enquiry',{exact:true}).click();
 await expect(detail.locator('.conversation-original p')).toHaveText(message);
 await detail.getByText('View full original enquiry',{exact:true}).click();
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await mkdir('/tmp/luxxy-enquiry-tidy',{recursive:true});
 await page.screenshot({path:`/tmp/luxxy-enquiry-tidy/${width}.png`,fullPage:true});
 await detail.getByRole('button',{name:'Record the response',exact:true}).click();
 await expect(page.getByRole('dialog',{name:'Log another conversation'})).toBeVisible();
 await page.getByRole('button',{name:'Cancel',exact:true}).click();
 await expect(detail.getByRole('heading',{name:'Fictional Customer',exact:true})).toBeVisible();
 expect(writes).toEqual([]);expect(errors).toEqual([]);
});
